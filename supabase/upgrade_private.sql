create extension if not exists "pgcrypto";

-- ----------------------------------------------------------------------------
-- 1) profiles — supervisor & teachers (الملف الشخصي)
--    name + title + subjects + academic years
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id            uuid primary key default gen_random_uuid(),
  code          text unique not null, -- invite/login code (e.g. SAB-A1B2C3)
  role          text not null check (role in ('admin','teacher')),
  full_name     text not null,
  title         text, -- الصفة: أستاذ، محاضرة، معيد...
  subjects      text, -- المواد التي يدرسها (comma-separated)
  academic_year text, -- السنوات الدراسية (e.g. "السنة الثانية، الثالثة")
  schedule      text, -- أوقات المحاضرات الأسبوعية
  email         text,
  created_at    timestamptz not null default now(),
  created_by    uuid references public.profiles(id) on delete set null
);

-- ----------------------------------------------------------------------------
-- 2) invites — codes generated by supervisor Enas
-- ----------------------------------------------------------------------------
create table if not exists public.invites (
  code        text primary key, -- same as profile code when generated
  for_name    text not null, -- اسم الأستاذ المدعو
  role        text not null default 'teacher' check (role in ('teacher','admin')),
  created_by  uuid references public.profiles(id) on delete set null,
  used        boolean not null default false,
  used_by     uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 3) Owner isolation — add owner_id to existing tables
-- ----------------------------------------------------------------------------
alter table public.courses
  add column if not exists owner_id uuid references public.profiles(id) on delete cascade;
alter table public.lectures
  add column if not exists owner_id uuid references public.profiles(id) on delete cascade;
alter table public.students
  add column if not exists owner_id uuid references public.profiles(id) on delete cascade;

-- add schedule column if upgrading from old version
alter table public.profiles
  add column if not exists schedule text;

-- Also keep course ownership consistent: students owner derived from course owner
-- but we store owner_id directly for fast filtering.

-- ----------------------------------------------------------------------------
-- Indexes
-- ----------------------------------------------------------------------------
create index if not exists idx_profiles_code on public.profiles (code);
create index if not exists idx_profiles_role on public.profiles (role);
create index if not exists idx_invites_used on public.invites (used);
create index if not exists idx_courses_owner on public.courses (owner_id);
create index if not exists idx_lectures_owner on public.lectures (owner_id);
create index if not exists idx_students_owner on public.students (owner_id);

-- ----------------------------------------------------------------------------
-- RLS — keep anon permissive for classroom use (private via app-level checks)
-- ----------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.invites  enable row level security;

drop policy if exists "profiles_anon_all" on public.profiles;
drop policy if exists "invites_anon_all"  on public.invites;

create policy "profiles_anon_all"
  on public.profiles for all to anon using (true) with check (true);

create policy "invites_anon_all"
  on public.invites for all to anon using (true) with check (true);

