// مشترك بين الخادم والمتصفح — تحويل نتيجة Gemini إلى Markdown نظيف للتصدير
// Used both server (lectures_history.generated_markdown) and client (Save As .md/.txt)

export type GeminiResult = {
  summary: string;
  core_concepts: { term: string; definition: string; classroom_link: string }[];
  key_takeaways: string[];
  libyan_applications: string[]; // نحتفظ بالاسم للتوافق — هو نفسه Course Applications
  scenario_qa: { question: string; model_answer: string }[];
  reflection_tasks: { title: string; prompt: string; type: string }[];
  discussion_questions: string[];
};

export function generateMarkdown(data: GeminiResult, opts: { title?: string; createdAt?: string; model?: string; outputLanguage?: string } = {}): string {
  const title = opts.title?.trim() || (opts.outputLanguage === "ar" ? "محاضرة بدون عنوان" : "Untitled Lecture");
  const date = opts.createdAt ? new Date(opts.createdAt).toLocaleString(opts.outputLanguage === "ar" ? "ar-EG" : "en-US") : new Date().toLocaleString();
  const langNote = opts.outputLanguage ? ` | Language: ${opts.outputLanguage}` : "";
  const modelNote = opts.model ? ` | Model: ${opts.model}` : "";

  const lines: string[] = [];

  lines.push(`# ${title}`);
  lines.push(``);
  lines.push(`> ${opts.outputLanguage === "ar" ? "تم التوليد" : "Generated"}: ${date}${langNote}${modelNote}`);
  lines.push(`> SABRATHA ELT Tech-Assistant — Faculty of Arts & Education — Sabratha University`);
  lines.push(``);
  lines.push(`---`);
  lines.push(``);

  // الملخص
  lines.push(`## ${opts.outputLanguage === "ar" ? "الملخص التربوي" : "Pedagogical Summary"}`);
  lines.push(``);
  lines.push(data.summary || "");
  lines.push(``);

  // المفاهيم الجوهرية
  if (data.core_concepts?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "المفاهيم الجوهرية" : "Core Concepts"}`);
    lines.push(``);
    for (const c of data.core_concepts) {
      lines.push(`- **${c.term}**: ${c.definition}`);
      if (c.classroom_link) lines.push(`  - _${opts.outputLanguage === "ar" ? "الربط الصفي" : "Classroom link"}_: ${c.classroom_link}`);
    }
    lines.push(``);
  }

  // النقاط الأساسية
  if (data.key_takeaways?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "أهم الاستنتاجات" : "Key Takeaways"}`);
    lines.push(``);
    for (const k of data.key_takeaways) lines.push(`- ${k}`);
    lines.push(``);
  }

  // التطبيقات للصف المعياري
  if (data.libyan_applications?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "تطبيقات للصف المعياري" : "Course Context Applications"}`);
    lines.push(``);
    for (const a of data.libyan_applications) lines.push(`- ${a}`);
    lines.push(``);
  }

  // سيناريوهات
  if (data.scenario_qa?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "سيناريوهات — أسئلة وأجوبة نموذجية" : "Scenarios — Q&A"}`);
    lines.push(``);
    data.scenario_qa.forEach((qa, i) => {
      lines.push(`### ${opts.outputLanguage === "ar" ? "سيناريو" : "Scenario"} ${i + 1}: ${qa.question}`);
      lines.push(``);
      lines.push(`**${opts.outputLanguage === "ar" ? "إجابة نموذجية" : "Model Answer"}:** ${qa.model_answer}`);
      lines.push(``);
    });
  }

  // مهام تأمل
  if (data.reflection_tasks?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "مهام التأمل" : "Reflection Tasks"}`);
    lines.push(``);
    for (const t of data.reflection_tasks) {
      lines.push(`- **${t.title}** _(${t.type})_: ${t.prompt}`);
    }
    lines.push(``);
  }

  // أسئلة نقاش
  if (data.discussion_questions?.length) {
    lines.push(`## ${opts.outputLanguage === "ar" ? "أسئلة النقاش" : "Discussion Questions"}`);
    lines.push(``);
    for (const q of data.discussion_questions) lines.push(`- ${q}`);
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`_${opts.outputLanguage === "ar" ? "تم إنشاؤه عبر مساعد تكنولوجيا تدريس اللغة الإنجليزية — جامعة صبراتة" : "Generated by SABRATHA ELT Tech-Assistant — Sabratha University"}_`);

  return lines.join("\n");
}

// تحويل Markdown إلى نص عادي للتصدير .txt (إزالة علامات Markdown بسيطة)
export function markdownToPlainText(md: string): string {
  return md
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/\*(.+?)\*/g, "$1")
    .replace(/_(.+?)_/g, "$1")
    .replace(/^>\s?/gm, "")
    .replace(/^---$/gm, "----------------------------------------")
    .trim();
}

// اسم ملف آمن من العنوان
export function safeFileName(title: string, fallback = "lecture"): string {
  const base = (title || fallback)
    .trim()
    .replace(/[^a-zA-Z0-9\u0600-\u06FF_\- ]/g, "")
    .replace(/\s+/g, "_")
    .slice(0, 60) || fallback;
  return base;
}
